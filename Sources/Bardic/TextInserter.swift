import AppKit
import ApplicationServices

/// Inserts text at the cursor of the frontmost app by pasting, then restores the user's clipboard.
@MainActor
enum TextInserter {
    static func insert(_ text: String) async {
        let pb = NSPasteboard.general
        let saved = snapshot(pb)

        // Like clearContents(), but keeps the dictation off Universal Clipboard (the user's other devices).
        _ = pb.prepareForNewContents(with: .currentHostOnly)
        pb.setString(text, forType: .string)
        // Ask clipboard managers and history tools to ignore this temporary entry (nspasteboard.org markers).
        for marker in ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType",
                       "org.nspasteboard.AutoGeneratedType"] {
            pb.setData(Data(), forType: NSPasteboard.PasteboardType(marker))
        }
        let changeCount = pb.changeCount

        pressCmdV()

        // Give the target app time to read the pasteboard before restoring it. Busy apps (Electron,
        // VMs, remote desktops, an app that was just activated) can take well over 300 ms to act on ⌘V;
        // restoring too early would paste the previous clipboard instead. Stays awaited so a second
        // dictation can't snapshot this one's text as "the user's clipboard".
        try? await Task.sleep(nanoseconds: 1_000_000_000)
        if pb.changeCount == changeCount {
            restore(saved, to: pb)
        }
    }

    private static func pressCmdV() {
        let src = CGEventSource(stateID: .combinedSessionState)
        let vKey: CGKeyCode = 9
        let down = CGEvent(keyboardEventSource: src, virtualKey: vKey, keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: vKey, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cgAnnotatedSessionEventTap)
        up?.post(tap: .cgAnnotatedSessionEventTap)
    }

    private static func snapshot(_ pb: NSPasteboard) -> [[NSPasteboard.PasteboardType: Data]] {
        (pb.pasteboardItems ?? []).map { item in
            var dict: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { dict[type] = data }
            }
            return dict
        }
    }

    /// Puts the user's own clipboard back exactly as it was. clearContents() also drops the
    /// current-host-only option set in insert(), so the restored clipboard syncs as it did before.
    private static func restore(_ items: [[NSPasteboard.PasteboardType: Data]], to pb: NSPasteboard) {
        pb.clearContents()
        guard !items.isEmpty else { return }
        let objects: [NSPasteboardItem] = items.map { dict in
            let item = NSPasteboardItem()
            for (type, data) in dict { item.setData(data, forType: type) }
            return item
        }
        pb.writeObjects(objects)
    }
}
